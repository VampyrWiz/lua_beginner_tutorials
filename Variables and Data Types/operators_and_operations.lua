-- Arithmetic Operations
local num1 = 9
local num2 = 2
print(num1.." + "..num2.." = "..(num1 + num2))
print(num1.." - "..num2.." = "..(num1 - num2))
print(num1.." * "..num2.." = "..(num1 * num2))
print(num1.." / "..num2.." = "..(num1 / num2))
print(num1.." % "..num2.." = "..(num1 % num2))
print(num1.." // "..num2.." = "..(num1 // num2))
print(num1.." ^ "..num2.." = "..(num1 ^ num2))
print("\n")

-- Relational Operations
print(10 == 15)
print(10 ~= 15)
print(10 < 15)
print(10 > 15)
print(15 >= 15)
print(10 <= 15)
print("\n")

-- Logical operation
print(not true)
print(true and false)
print(true and true)
print(false or false)
print(true or false)