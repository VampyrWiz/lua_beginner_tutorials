-- \n -> New Line
print("Hello World!\nWelcome to Lua Programming.")

-- \t -> Horizontal Tab
print("Name:\tJohn Smirk")

-- \\ -> Backslash
print("\\home\\user\\Downloads")

-- \" and \'
print("\"Mahabharata\" by \'Vedavyasa\'")

-- \r -> Carriage return (Beginning of current line)
print("Hello\rWorld")

-- \v -> Vertical Tab
print("Hello World!\vWelcome to Lua Programming.")